#include "libft.h"
#include <stdlib.h>

char	*ft_substr(char const *s, unsigned int start, size_t len)
{
	char	*subs;
	size_t	i;

	i = 0;
	start = (size_t)start;
	subs = (char *)malloc(len);
	if (!(subs) || len == 0)
		return (NULL);
	while (s[start] != '\0' && i < len)
	{
		subs[i] = s[start];
		i++;
		start++;
	}
	return (subs);
}
